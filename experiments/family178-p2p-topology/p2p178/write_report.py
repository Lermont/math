def interval(stat, scale=1, digits=2):
    if stat["median"] is None:
        return "—"
    return f"{stat['median']*scale:.{digits}f} [{stat['min']*scale:.{digits}f}–{stat['max']*scale:.{digits}f}]"


def threshold(row, q, scale=.001, digits=3):
    censored = row[f"t{q}_censored_messages"]
    return f"не достигнут {censored}/{row['messages']}" if censored else interval(row[f"t{q}_ms"], scale, digits)


